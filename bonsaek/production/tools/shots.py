def cast_block(cast):
    return "  등장: " + " / ".join(CHAR[c] for c in cast) if cast else "  등장 인물 없음(사물·배경만)."


def panel_text(p):
    lines = [p["desc"]]
    if p.get("hands"):
        lines.append("  손(반드시 지킬 것): " + p["hands"])
    if p.get("space"):
        lines.append("  말풍선 자리: " + p["space"] + " 이 부분은 단순한 배경으로 비워 둔다.")
    lines.append(cast_block(p.get("cast", [])))
    if p.get("text"):
        lines.append("  글자(이 컷 안에만, 정확히): " + p["text"])
    else:
        lines.append("  이 컷에는 어떤 글자도 넣지 않는다.")
    return "\n".join(lines)


def build(shot):
    parts = [STYLE, COLOR[shot["color"]], ANATOMY]
    if shot.get("layout") == "stack2":
        parts.append(STACK2)
        for i, p in enumerate(shot["panels"], 1):
            parts.append("[컷%d — 높이 약 %d%%] %s" % (i, p["h"], panel_text(p)))
    else:
        parts.append(SINGLE)
        parts.append("[컷] " + panel_text(shot))
    parts.append(TEXT)
    return "\n".join(parts)


def refs_for(shot):
    cast = set(shot.get("cast", []))
    for p in shot.get("panels", []):
        cast |= set(p.get("cast", []))
    order = ["SH4", "SH1", "SH2", "SH3", "SH5"]
    need = {SHEET_OF[c] for c in cast if c in SHEET_OF}
    return [SHEET_FILE[s] for s in order if s in need][:3]


