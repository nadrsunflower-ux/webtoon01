def emit(ids, n=2):
    jobs = []
    (ROOT / "raw" / "_cand").mkdir(parents=True, exist_ok=True)
    for s in SHOTS:
        if ids and s["id"] not in ids:
            continue
        (PROMPTS / (s["id"] + ".txt")).write_text(build(s))
        for k in range(1, n + 1):
            jobs.append({"out": "raw/_cand/%s%d.png" % (s["id"], k), "prompt_file": "prompts/%s.txt" % s["id"],
                         "aspect_ratio": s["ar"], "quality": "high", "moderation": "low", "refs": refs_for(s)})
    (ROOT / "batch_restage.json").write_text(json.dumps(jobs, ensure_ascii=False, indent=1))
    return jobs


