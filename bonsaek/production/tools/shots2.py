def who(c, o=None, chin=None):
    t = FACE[c]
    if o:
        t += " 이날의 옷: " + OUTFIT[o]
    if chin:
        t += " " + CHIN[chin]
    return t


def cast_block(cast):
    if not cast:
        return "  등장 인물 없음(사물·배경만)."
    return "  등장: " + " / ".join(who(*c) for c in cast)


def panel_text(p):
    lines = [p["desc"]]
    if p.get("hands"):
        lines.append("  손(반드시 지킬 것): " + p["hands"])
    if p.get("space"):
        lines.append("  말풍선 자리: " + p["space"] + " 이 부분은 단순한 배경으로 비워 둔다.")
    lines.append(cast_block(p.get("cast", [])))
    lines.append(("  글자(이 컷 안에만, 정확히): " + p["text"]) if p.get("text") else "  이 컷에는 어떤 글자도 넣지 않는다.")
    return "\n".join(lines)


def all_cast(shot):
    cast = list(shot.get("cast", []))
    for p in shot.get("panels", []):
        cast += p.get("cast", [])
    return cast


def build(shot):
    parts = [STYLE, COLOR[shot["color"]], ANATOMY]
    if shot.get("kids"):
        parts.append(EXTRAS)
    if shot.get("seats"):
        parts.append(SEATS[shot["seats"]])
    if shot.get("layout") == "stack2":
        parts.append(STACK2)
        for i, p in enumerate(shot["panels"], 1):
            parts.append("[컷%d — 높이 약 %d%%] %s" % (i, p["h"], panel_text(p)))
    else:
        parts.append(SINGLE)
        parts.append("[컷] " + panel_text(shot))
    parts.append(TEXT2)
    return "\n".join(parts)


