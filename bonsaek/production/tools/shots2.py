def emit(shots, group):
    jobs = []
    for s in shots:
        sid = s["id"]
        if "prompt" in s:
            text, refs, out = s["prompt"], s.get("refs", []), "sheets/%s.png" % sid
        else:
            text, refs, out = build(s), refs_for(s), "raw/%s.png" % sid
        (PROMPTS / ("%s.txt" % sid)).write_text(text)
        jobs.append({"out": out, "prompt_file": "prompts/%s.txt" % sid, "aspect_ratio": s["ar"],
                     "quality": "high", "moderation": "low", "refs": refs})
    (ROOT / ("batch_%s.json" % group)).write_text(json.dumps(jobs, ensure_ascii=False, indent=1))
    return jobs


